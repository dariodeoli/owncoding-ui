// @vitest-environment jsdom
import React, { createRef, useState } from 'react'
import { afterEach, describe, expect, test, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { TimeInput } from '../src/index.js'

afterEach(cleanup)
const editar = (input, texto) => fireEvent.change(input, { target: { value: texto } })
function Controlado({ inicial = '', ...props }) {
  const [valor, setValor] = useState(inicial)
  return <><TimeInput aria-label="Hora" value={valor} onValueChange={setValor} {...props} /><output>{valor}</output></>
}

describe('TimeInput: contrato aditivo', () => {
  test.each([['8', '08:00'], ['830', '08:30'], ['8:30', '08:30'], ['23:59', '23:59'], ['', '']])('confirma %s como %s sin redondear', (texto, esperado) => {
    const cambiar = vi.fn()
    render(<TimeInput aria-label="Hora" onValueChange={cambiar} defaultValue="12:00" name="hora" />)
    const input = screen.getByRole('textbox')
    editar(input, texto)
    expect(input.value).toBe(texto)
    fireEvent.blur(input)
    expect(input.value).toBe(esperado)
    expect(cambiar).toHaveBeenCalledWith(esperado)
  })
  test.each(['25:99', '24:00', '8:3', '12345', 'hola'])('preserva borrador inválido %s y lo enlaza al error', (texto) => {
    const cambiar = vi.fn()
    render(<TimeInput aria-label="Hora" defaultValue="12:00" name="hora" onValueChange={cambiar} aria-describedby="ayuda" />)
    const input = screen.getByRole('textbox')
    editar(input, texto)
    fireEvent.blur(input)
    expect(input.value).toBe(texto)
    expect(input.validity.customError).toBe(true)
    expect(input.getAttribute('aria-invalid')).toBe('true')
    expect(input.getAttribute('aria-describedby')).toBe(`ayuda ${screen.getByRole('alert').id}`)
    expect(document.querySelector('input[type="hidden"]').value).toBe('')
    expect(cambiar).not.toHaveBeenCalled()
    editar(input, '8:30')
    fireEvent.blur(input)
    expect(input.validity.valid).toBe(true)
    expect(screen.queryByRole('alert')).toBeNull()
  })
  test('controlado acepta actualizaciones externas y confirma sin depender del callback para detectar el modo', () => {
    const { rerender } = render(<TimeInput aria-label="Hora" value="09:00" />)
    const input = screen.getByRole('textbox')
    editar(input, '10:00'); fireEvent.blur(input)
    expect(input.value).toBe('09:00')
    rerender(<TimeInput aria-label="Hora" value="11:30" />)
    expect(input.value).toBe('11:30')
    rerender(<TimeInput aria-label="Hora" value="" />)
    expect(input.value).toBe('')
  })
  test('value presente undefined sigue siendo controlado; compone onInvalid', () => {
    const invalidar = vi.fn()
    render(<TimeInput aria-label="Hora" value={undefined} defaultValue="09:00" onInvalid={invalidar} />)
    const input = screen.getByRole('textbox')
    expect(input.value).toBe('')
    editar(input, '10'); fireEvent.blur(input)
    expect(input.value).toBe('')
    fireEvent.invalid(input)
    expect(invalidar).toHaveBeenCalledOnce()
  })
  test('controlado comunica confirmaciones con onValueChange', () => {
    render(<Controlado inicial="09:00" />)
    const input = screen.getByRole('textbox')
    editar(input, '1030'); fireEvent.blur(input)
    expect(input.value).toBe('10:30')
    expect(screen.getByRole('status').textContent).toBe('10:30')
  })
  test('flechas: default un minuto, paso explícito y límites sin wrap ni redondeo', () => {
    const { rerender } = render(<TimeInput aria-label="Hora" defaultValue="08:07" />)
    const input = screen.getByRole('textbox')
    fireEvent.keyDown(input, { key: 'ArrowUp' }); expect(input.value).toBe('08:08')
    fireEvent.keyDown(input, { key: 'ArrowDown' }); expect(input.value).toBe('08:07')
    rerender(<TimeInput aria-label="Hora" stepMinutes={15} min="08:00" max="08:15" />)
    fireEvent.keyDown(input, { key: 'ArrowUp' }); expect(input.value).toBe('08:15')
    fireEvent.keyDown(input, { key: 'ArrowUp' }); expect(input.value).toBe('08:15')
    fireEvent.keyDown(input, { key: 'ArrowDown' }); expect(input.value).toBe('08:00')
    editar(input, '08:07'); fireEvent.blur(input); expect(input.value).toBe('08:07')
  })
  test('límites del día y paso inválido usa un minuto', () => {
    render(<TimeInput aria-label="Hora" defaultValue="23:59" stepMinutes={0} />)
    const input = screen.getByRole('textbox')
    fireEvent.keyDown(input, { key: 'ArrowUp' }); expect(input.value).toBe('23:59')
    editar(input, '00:00'); fireEvent.blur(input)
    fireEvent.keyDown(input, { key: 'ArrowDown' }); expect(input.value).toBe('00:00')
    fireEvent.keyDown(input, { key: 'ArrowUp' }); expect(input.value).toBe('00:01')
  })
  test('rango explícito se aplica al texto, Enter conserva y bloquea inválido', () => {
    const cambiar = vi.fn()
    render(<TimeInput aria-label="Hora" min="09:00" max="18:00" onValueChange={cambiar} />)
    const input = screen.getByRole('textbox')
    editar(input, '830')
    expect(fireEvent.keyDown(input, { key: 'Enter' })).toBe(false)
    expect(input.value).toBe('830')
    expect(screen.getByRole('alert').textContent).toContain('rango')
    expect(cambiar).not.toHaveBeenCalled()
    editar(input, '930'); fireEvent.keyDown(input, { key: 'Enter' })
    expect(input.value).toBe('09:30')
  })
  test('ref apunta al input, etiqueta y onKeyDown preventDefault conserva valor', () => {
    const ref = createRef()
    const key = vi.fn(evento => evento.preventDefault())
    render(<><label htmlFor="hora">Inicio</label><TimeInput id="hora" ref={ref} defaultValue="09:00" onKeyDown={key} /></>)
    expect(ref.current).toBe(screen.getByLabelText('Inicio'))
    ref.current.focus(); expect(document.activeElement).toBe(ref.current)
    fireEvent.keyDown(ref.current, { key: 'ArrowUp' })
    expect(key).toHaveBeenCalledOnce()
    expect(ref.current.value).toBe('09:00')
  })
  test('required, disabled y readOnly conservan semántica', () => {
    const { rerender } = render(<TimeInput aria-label="Hora" required />)
    const input = screen.getByRole('textbox')
    fireEvent.blur(input)
    expect(input.validity.valid).toBe(false)
    expect(screen.getByRole('alert').textContent).toBe('Ingresá una hora.')
    rerender(<TimeInput aria-label="Hora" required disabled />)
    expect(input.disabled).toBe(true)
    expect(input.validity.customError).toBe(false)
    rerender(<TimeInput aria-label="Hora" readOnly value="09:00" />)
    fireEvent.keyDown(input, { key: 'ArrowUp' })
    expect(input.readOnly).toBe(true)
    expect(input.value).toBe('09:00')
  })
  test('noValidate bloquea submit, evita valor previo y enfoca el borrador inválido', () => {
    const enviar = vi.fn(evento => evento.preventDefault())
    render(<form noValidate onSubmit={enviar}><TimeInput aria-label="Hora" name="hora" defaultValue="09:00" /><button>Enviar</button></form>)
    const input = screen.getByRole('textbox'), form = input.form
    editar(input, '25:99')
    expect(fireEvent.submit(form)).toBe(false)
    expect(enviar).not.toHaveBeenCalled()
    expect(document.activeElement).toBe(input)
    expect(new FormData(form).get('hora')).toBe('')
    expect(screen.getByRole('alert')).toBeTruthy()
  })
  test('submit confirma atajo antes de ejecutar onSubmit (controlado)', () => {
    const enviar = vi.fn()
    function Formulario() {
      const [hora, setHora] = useState('09:00')
      return <form noValidate onSubmit={evento => { evento.preventDefault(); enviar(hora, new FormData(evento.currentTarget).get('hora')) }}><TimeInput aria-label="Hora" name="hora" value={hora} onValueChange={setHora} /></form>
    }
    render(<Formulario />)
    const input = screen.getByRole('textbox')
    editar(input, '830'); fireEvent.submit(input.form)
    expect(enviar).toHaveBeenCalledWith('08:30', '08:30')
  })
  test('el guard precede onSubmitCapture de React y sincroniza atajos antes de persistir', () => {
    const capturar = vi.fn(), enviar = vi.fn()
    function Formulario() {
      const [hora, setHora] = useState('09:00')
      return <form noValidate onSubmitCapture={evento => capturar(hora, new FormData(evento.currentTarget).get('hora'))} onSubmit={evento => { evento.preventDefault(); enviar(hora) }}><TimeInput aria-label="Hora" name="hora" value={hora} onValueChange={setHora} /></form>
    }
    render(<Formulario />)
    const input = screen.getByRole('textbox')
    editar(input, '25:99'); fireEvent.submit(input.form)
    expect(capturar).not.toHaveBeenCalled()
    expect(enviar).not.toHaveBeenCalled()
    expect(document.activeElement).toBe(input)
    editar(input, '830'); fireEvent.submit(input.form)
    expect(capturar).toHaveBeenCalledWith('08:30', '08:30')
    expect(enviar).toHaveBeenCalledWith('08:30')
  })
  test('el guard ignora otros formularios', () => {
    const enviar = vi.fn(evento => evento.preventDefault())
    render(<><form aria-label="Otro" noValidate onSubmit={enviar} /><form><TimeInput aria-label="Hora" required /></form></>)
    fireEvent.submit(screen.getByRole('form', { name: 'Otro' }))
    expect(enviar).toHaveBeenCalledOnce()
  })
  test('asociación form externa y reset no controlado', async () => {
    const enviar = vi.fn(evento => evento.preventDefault())
    render(<><form id="externo" noValidate onSubmit={enviar} /><TimeInput aria-label="Hora" form="externo" name="hora" defaultValue="09:00" /></>)
    const input = screen.getByRole('textbox')
    editar(input, '25:99'); fireEvent.submit(input.form)
    expect(enviar).not.toHaveBeenCalled()
    editar(input, '10'); fireEvent.blur(input)
    expect(new FormData(input.form).get('hora')).toBe('10:00')
    await act(async () => { fireEvent.reset(input.form) })
    expect(input.value).toBe('09:00')
    expect(new FormData(input.form).get('hora')).toBe('09:00')
  })
  test('reset cancelado conserva borrador y valor confirmado', async () => {
    render(<form onReset={evento => evento.preventDefault()}><TimeInput aria-label="Hora" name="hora" defaultValue="09:00" /></form>)
    const input = screen.getByRole('textbox')
    editar(input, '10'); fireEvent.blur(input)
    editar(input, '25:99'); fireEvent.blur(input)
    await act(async () => { fireEvent.reset(input.form) })
    expect(input.value).toBe('25:99')
    expect(input.validity.customError).toBe(true)
    editar(input, '1030'); fireEvent.blur(input)
    await act(async () => { fireEvent.reset(input.form) })
    expect(input.value).toBe('10:30')
    expect(new FormData(input.form).get('hora')).toBe('10:30')
  })
  test('submit síncrono desde onChange lee el borrador DOM actual', () => {
    const enviar = vi.fn()
    function Formulario() {
      const [hora, setHora] = useState('09:00')
      return <form noValidate onSubmit={evento => { evento.preventDefault(); enviar(hora, new FormData(evento.currentTarget).get('hora')) }}><TimeInput aria-label="Hora" name="hora" value={hora} onValueChange={setHora} onChange={evento => evento.target.form.requestSubmit()} /></form>
    }
    render(<Formulario />)
    const input = screen.getByRole('textbox')
    editar(input, '25:99')
    expect(enviar).not.toHaveBeenCalled()
    expect(input.value).toBe('25:99')
    editar(input, '830')
    expect(enviar).toHaveBeenCalledWith('08:30', '08:30')
  })
  test('desmontar elimina el bloqueo del formulario que permanece', () => {
    const enviar = vi.fn(evento => evento.preventDefault())
    const { rerender } = render(<form noValidate onSubmit={enviar}><TimeInput aria-label="Hora" required /></form>)
    const formulario = screen.getByRole('textbox').form
    fireEvent.submit(formulario)
    expect(enviar).not.toHaveBeenCalled()
    rerender(<form noValidate onSubmit={enviar} />)
    fireEvent.submit(formulario)
    expect(enviar).toHaveBeenCalledOnce()
  })
  test('disabled no bloquea noValidate y se omite del payload', () => {
    const enviar = vi.fn(evento => evento.preventDefault())
    render(<form noValidate onSubmit={enviar}><TimeInput aria-label="Hora" name="hora" required disabled /></form>)
    const input = screen.getByRole('textbox')
    fireEvent.submit(input.form)
    expect(enviar).toHaveBeenCalledOnce()
    expect(new FormData(input.form).has('hora')).toBe(false)
  })
})
